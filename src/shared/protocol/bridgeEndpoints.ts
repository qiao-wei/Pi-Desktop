/**
 * Boundary `bridge`: the renderer ↔ bridge HTTP/NDJSON surface.
 *
 * Two layers of contract live here, on purpose:
 *
 * 1. **Typed core** (`BRIDGE_ENDPOINTS`) - the endpoints a change to is a protocol change:
 *    the handshake, the snapshot, the turn stream, stop, session switch. Each carries its
 *    `since` version, its transport and what it is for. Typed request/response shapes are
 *    declared next to it as the protocol's named types.
 *
 * 2. **Frozen surface** (`architecture/generated/bridge-surface.json`) - every route the
 *    bridge answers and every `/api/...` path a renderer file names, generated from the code
 *    and verified byte-for-byte by `scripts/architecture/check.mjs`. The core above is a
 *    subset of it; the frozen surface is what makes an *undocumented* route impossible,
 *    because adding one on either side fails `npm test` until it is regenerated.
 *
 * Why generated rather than hand-written: a hand-maintained list of ~90 routes would be stale
 * within a week, and a stale protocol list is worse than none - it teaches readers to ignore
 * it. Generated + verified means the file is always true, and the *meaning* of each route is
 * added by hand only where it matters (the core).
 */

/** The version both sides of the boundary must agree on. See `./version.ts`. */
export interface BridgeHandshake {
  /** `PROTOCOL_VERSION` as the bridge compiled it. */
  protocolVersion: number;
  /** Bridge process id - useful when two bridges are alive and the UI talks to the wrong one. */
  pid?: number;
}

export type BridgeEndpointTransport = "json" | "ndjson";

export interface BridgeEndpointContract {
  readonly method: "GET" | "POST";
  readonly path: string;
  readonly transport: BridgeEndpointTransport;
  /** Protocol version that introduced this endpoint. */
  readonly since: number;
  readonly summary: string;
}

